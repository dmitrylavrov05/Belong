  await c.waitForTimeout(500);
  log('url', c.url(), 'step', await c.locator('#book').getAttribute('data-step'));
  log('dock', await c.locator('.book-dock').innerText());
  await c.screenshot({ path: SHOT + 'b02-book.png', fullPage: true });
  // add an extra
  const extras = c.locator('.svc-extra input');
  log('extras', await extras.count());
  if (await extras.count()) await extras.first().check();
  log('dock2', await c.locator('.book-dock').innerText());
  await c.locator('[data-action="to-time"]').click();
  await c.getByRole('button', { name: /Завтра/ }).click();
  const free = c.locator('.slot:not([disabled])');
  log('free slots', await free.count());
  await free.nth(2).click();
  await c.locator('[data-action="confirm"]').click();
