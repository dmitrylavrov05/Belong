// Спільне для панелі бізнесу (business.js) і адмінки CARCAR (admin.js).
// Перевірки локальні: формат і контрольні суми. Звірку з ЄДР і банком робить модератор
// (а в робочій версії — сервер через офіційні реєстри).

const digits = (s) => [...String(s)].map(Number);

// РНОКПП (ідентифікаційний номер ФОП): 10 цифр, остання — контрольна.
export function rnokppValid(code) {
  if (!/^\d{10}$/.test(code)) return false;
  const d = digits(code);
  const w = [-1, 5, 7, 9, 4, 6, 10, 5, 7];
  return (w.reduce((a, k, i) => a + k * d[i], 0) % 11) % 10 === d[9];
}

// Код ЄДРПОУ юридичної особи: 8 цифр, остання — контрольна; ваги залежать від діапазону коду.
export function edrpouValid(code) {
  if (!/^\d{8}$/.test(code)) return false;
  const d = digits(code);
  const n = Number(code);
  const w = n < 30000000 || n > 60000000 ? [1, 2, 3, 4, 5, 6, 7] : [7, 1, 2, 3, 4, 5, 6];
  let s = w.reduce((a, k, i) => a + k * d[i], 0) % 11;
  if (s === 10) {
    s = w.reduce((a, k, i) => a + (k + 2) * d[i], 0) % 11;
    if (s === 10) s = 0;
  }
  return s === d[7];
}

export const codeValid = (type, code) => (type === 'fop' ? rnokppValid(code) : edrpouValid(code));

export const normIban = (s) => String(s ?? '').replace(/\s+/g, '').toUpperCase();

// Український IBAN: UA, 2 контрольні цифри, 6 цифр МФО банку й 19 символів рахунку; перевірка mod 97.
export function ibanValid(raw) {
  const iban = normIban(raw);
  if (!/^UA\d{27}$/.test(iban)) return false;
  const moved = `${iban.slice(4)}${iban.slice(0, 4)}`.replace(/[A-Z]/g, (c) => String(c.charCodeAt(0) - 55));
  let r = 0;
  for (const ch of moved) r = (r * 10 + Number(ch)) % 97;
  return r === 1;
}

export const formatIban = (raw) => normIban(raw).replace(/(.{4})/g, '$1 ').trim();

// Банк за МФО (цифри 5–10 IBAN) — для підказки; невідомий МФО просто показуємо числом.
const BANKS = {
  305299: 'ПриватБанк', 322001: 'Універсал Банк (monobank)', 300465: 'Ощадбанк', 334851: 'ПУМБ',
  380805: 'Райффайзен Банк', 351005: 'УКРСИББАНК', 307770: 'А-Банк', 300346: 'Сенс Банк',
};
export function ibanBank(raw) {
  const mfo = normIban(raw).slice(4, 10);
  return mfo.length === 6 ? `${BANKS[mfo] ?? 'Банк'} (МФО ${mfo})` : '';
}

