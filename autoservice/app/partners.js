// Що ще не заповнено, щоб надіслати заявку на перевірку. Порожній список — можна надсилати.
export function missingSteps(partner) {
  const c = partner.company ?? {};
  const out = [];
  if (!c.type || !c.name?.trim() || !codeValid(c.type, c.code ?? '') || !c.tax || !c.email?.trim() || !c.phone?.trim() || (c.type === 'tov' && !c.director?.trim())) out.push('Юридична особа');
  if (!DOCS.filter(([, , req]) => req).every(([id]) => partner.docs?.[id])) out.push('Документи');
  const pay = partner.payout ?? {};
  if (!ibanValid(pay.iban) || !pay.holder?.trim() || pay.code !== c.code) out.push('Реквізити для виплат');
  if (partner.offer?.version !== OFFER.version) out.push('Договір-оферта');
  return out;
}

